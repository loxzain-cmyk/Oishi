const esc = value =>
  String(value).replace(/[&<>"']/g, char => ({
    "&": "&amp;",
    "<": "&lt;",
    ">": "&gt;",
    '"': "&quot;",
    "'": "&#39;"
  }[char]));

function videoCard(project, index, organisation) {
  const [title, url, videoId, category] = project;

  const thumbnail = videoId
    ? `<img loading="lazy"
         src="https://img.youtube.com/vi/${videoId}/hqdefault.jpg"
         alt="${esc(title)} thumbnail"
         onerror="this.style.display='none'">`
    : "";

  return `
    <article class="card">
      <a class="thumb" href="${url}" target="_blank" rel="noopener noreferrer">
        ${thumbnail}
        <span class="num">${String(index + 1).padStart(2, "0")}</span>
        <span class="play">${videoId ? "▶" : "↗"}</span>
      </a>
      <div class="body">
        <p class="type">${esc(category)}</p>
        <h3 class="title">${esc(title)}</h3>
        <div class="foot">
          <span>${esc(organisation)}</span>
          <a href="${url}" target="_blank" rel="noopener noreferrer">
            ${videoId ? "WATCH ↗" : "VIEW POST ↗"}
          </a>
        </div>
      </div>
    </article>
  `;
}

/* Editorial poster-style card.
   Reuses the existing CETL editorial design classes. */
function editorialPoster(project, index, organisation, category = "POSTER DESIGN") {
  const [title, url] = project;

  const isPoem = category === "POEM";
  const description = isPoem
    ? "A written piece exploring memory, emotion and reflection."
    : "A visual story created to highlight literature, culture and meaningful occasions.";

  return `
    <article class="editorial ${index % 2 ? "reverse" : ""}">
      <a class="visual" href="${url}" target="_blank" rel="noopener noreferrer"
         aria-label="Open ${esc(title)}">
        <span class="ulabian-visual-title">${esc(title)}</span>
        <small>${esc(organisation)} · ${esc(category)}</small>
      </a>
      <div class="editorial-copy">
        <p class="type">${esc(category)} / ${String(index + 1).padStart(2, "0")}</p>
        <h4>${esc(title)}</h4>
        <p>${description}</p>
        <a href="${url}" target="_blank" rel="noopener noreferrer">
          ${isPoem ? "READ POEM ↗" : "VIEW ORIGINAL POST ↗"}
        </a>
      </div>
    </article>
  `;
}

function renderEditorialRows(items, organisation, category, startIndex = 0) {
  const rows = [];

  for (let i = 0; i < items.length; i += 2) {
    const rowItems = items.slice(i, i + 2);

    rows.push(`
      <div class="editorial-row">
        ${rowItems.map((project, j) =>
          editorialPoster(
            project,
            startIndex + i + j,
            organisation,
            category
          )
        ).join("")}
      </div>
    `);
  }

  return rows.join("");
}

